/* Builds content/i18n/REVIEW.md: every English string beside its Spanish and Arabic text, for a native-speaker review.
   Usage: npm run i18n:review */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, log } from "./lib.mjs";

const dir = join(ROOT, "brand-center-rectio/content/i18n");
const files = readdirSync(join(dir, "en")).filter((f) => f.endsWith(".json")).sort();
const flat = (v, path = "") => (Array.isArray(v) ? v.flatMap((x, i) => flat(x, `${path}[${i}]`)) : v && typeof v === "object" ? Object.entries(v).flatMap(([k, x]) => flat(x, path ? `${path}.${k}` : k)) : [[path, String(v)]]);
const cell = (s) => (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

let out = `# Translation review sheet

Generated by \`npm run i18n:review\`. Do not edit by hand: change the JSON files in \`content/i18n/<language>/\`.

Spanish and Arabic were written by Claude and have **not** been reviewed by a native speaker. For each row, check the meaning, tone (plain, warm, direct) and the terms in \`GLOSSARY.md\`, then fix the text in the JSON file.

`;
let rows = 0;
for (const f of files) {
  const [en, es, ar] = ["en", "es", "ar"].map((l) => Object.fromEntries(flat(JSON.parse(readFileSync(join(dir, l, f), "utf8")))));
  out += `## ${f.replace(".json", "")}\n\n| Key | English | Español | العربية |\n| --- | --- | --- | --- |\n`;
  for (const [k, v] of Object.entries(en)) { out += `| \`${k}\` | ${cell(v)} | ${cell(es[k])} | ${cell(ar[k])} |\n`; rows++; }
  out += "\n";
}
writeFileSync(join(dir, "REVIEW.md"), out);
log.ok(`content/i18n/REVIEW.md (${rows} strings)`);
